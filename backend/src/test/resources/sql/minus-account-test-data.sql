-- S15P21D105-534: 격리된 H2 테스트 DB에서 마이너스통장 API 테스트가 쓰는 fixture다.
-- 실제 MySQL 마이그레이션(V14)을 대체하지 않는다.
--
-- `account`, `transaction`, `transaction_category`는 카드 fixture도 만들고 지운다. 테스트 클래스
-- 실행 순서에 따라 서로의 스키마를 깨뜨리지 않도록 여기서도 매번 다시 만들고, 클래스 간 DROP
-- 순서를 신경 쓰지 않도록 `minus_account`에 account 외래키를 두지 않는다. 실제 V14에는 ERD대로
-- 복합 외래키가 있다.
--
-- 금액 정합 CHECK는 H2에서도 그대로 건다. 엔티티에는 CHECK 선언이 없어 ddl-auto가 만든 스키마로는
-- 검증되지 않으므로, 상환 로직이 제약을 깨뜨리면 이 fixture에서 잡히도록 한 것이다.
--
-- account_no_hash 와 next_interest_date 는 기준일·해시 키 의존을 피하려고 테스트에서 채운다.

DROP TABLE IF EXISTS notification;
DROP TABLE IF EXISTS `transaction`;
DROP TABLE IF EXISTS transaction_category;
DROP TABLE IF EXISTS minus_account;
-- ddl-auto가 엔티티로 만든 다른 도메인 테이블이 account를 참조하고 있어 그냥 DROP하면 실패한다.
-- CASCADE는 그 참조 제약만 함께 정리하며 상대 테이블을 지우지는 않는다. 각 도메인 fixture가
-- 자기 테이블을 다시 만들므로 제약이 사라져도 다른 테스트에 영향을 주지 않는다.
DROP TABLE IF EXISTS account CASCADE;

CREATE TABLE account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL
        CHECK (account_type IN ('DEMAND_DEPOSIT', 'MINUS', 'DEPOSIT', 'SAVINGS')),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'CLOSED')),
    balance BIGINT NOT NULL,
    last_transaction_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'KRW',
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    -- MINUS 계좌의 잔액은 0 이하여야 한다. 상환이 부호를 잘못 다루면 여기서 실패한다.
    CONSTRAINT chk_test_account_balance_by_type
        CHECK ((account_type = 'MINUS' AND balance <= 0)
            OR (account_type <> 'MINUS' AND balance >= 0))
);

CREATE TABLE minus_account (
    account_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_type VARCHAR(30) NOT NULL CHECK (account_type = 'MINUS'),
    limit_amount BIGINT NOT NULL CHECK (limit_amount > 0),
    used_amount BIGINT NOT NULL CHECK (used_amount >= 0 AND used_amount <= limit_amount),
    available_amount BIGINT NOT NULL CHECK (available_amount = limit_amount - used_amount),
    interest_rate DECIMAL(10,4) NOT NULL CHECK (interest_rate >= 0),
    accrued_interest BIGINT NOT NULL CHECK (accrued_interest >= 0),
    next_interest_date DATE,
    maturity_date DATE,
    overdue_days INT NOT NULL DEFAULT 0 CHECK (overdue_days >= 0),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE transaction_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    default_spending_type VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE `transaction` (
    transaction_id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_id BIGINT,
    card_id BIGINT,
    category_id BIGINT,
    transaction_date DATE NOT NULL,
    transaction_time TIME,
    transaction_type VARCHAR(30) NOT NULL
        CHECK (transaction_type IN ('INCOME', 'EXPENSE', 'TRANSFER')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    balance_after BIGINT,
    merchant_name VARCHAR(255),
    payment_method VARCHAR(30),
    spending_type VARCHAR(20),
    summary VARCHAR(255),
    memo VARCHAR(500),
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    internal_transfer BOOLEAN NOT NULL DEFAULT FALSE,
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    CONSTRAINT fk_test_minus_transaction_category
        FOREIGN KEY (category_id) REFERENCES transaction_category (category_id)
);

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message VARCHAR(4000) NOT NULL,
    source_type VARCHAR(50),
    source_id VARCHAR(100),
    dedupe_key CHAR(64),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    read_at TIMESTAMP,
    deleted_at TIMESTAMP
);

