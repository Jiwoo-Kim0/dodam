DROP TABLE IF EXISTS `transaction`;
DROP TABLE IF EXISTS transaction_category;
DROP TABLE IF EXISTS card_billing_statement;
DROP TABLE IF EXISTS card;
DROP TABLE IF EXISTS account;
DROP TABLE IF EXISTS financial_product_option;
DROP TABLE IF EXISTS financial_product;
DROP TABLE IF EXISTS financial_company;
DROP TABLE IF EXISTS financial_profile;

CREATE TABLE financial_profile (
    user_id BIGINT PRIMARY KEY,
    monthly_income BIGINT,
    annual_income BIGINT,
    payday INT,
    fixed_expense BIGINT,
    emergency_fund_target BIGINT,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE financial_company (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_code VARCHAR(30) NOT NULL UNIQUE,
    company_name VARCHAR(150) NOT NULL,
    sector VARCHAR(50)
);

CREATE TABLE financial_product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    external_product_code VARCHAR(100),
    product_type VARCHAR(30) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    join_way VARCHAR(255),
    saving_type VARCHAR(30),
    loan_type VARCHAR(30),
    special_condition TEXT,
    join_member TEXT,
    min_rate DECIMAL(10, 4),
    max_rate DECIMAL(10, 4),
    max_limit BIGINT,
    baseline_performance BIGINT,
    max_benefit_limit BIGINT,
    description TEXT,
    benefits JSON,
    synced_at TIMESTAMP NOT NULL
);

CREATE TABLE financial_product_option (
    product_option_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    term INT,
    rate DECIMAL(10, 4),
    preferred_rate DECIMAL(10, 4),
    rate_type VARCHAR(30),
    min_rate DECIMAL(10, 4),
    max_rate DECIMAL(10, 4),
    repayment_type VARCHAR(30),
    limit_amount BIGINT
);

CREATE TABLE account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    balance BIGINT NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'KRW',
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

-- card_no_encrypted 는 조회 API에서 쓰지 않으므로 엔티티에 매핑하지 않는다.
-- 실제 스키마와 동일하게 NOT NULL 로 두어 읽기 경로가 원문 컬럼에 의존하지 않음을 확인한다.
CREATE TABLE card (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    withdrawal_account_id BIGINT NOT NULL,
    withdrawal_account_type VARCHAR(30) NOT NULL,
    financial_product_id BIGINT,
    card_no_encrypted VARBINARY(512) NOT NULL,
    card_no_hash CHAR(64) NOT NULL,
    card_no_masked VARCHAR(100) NOT NULL,
    issuer_code VARCHAR(30) NOT NULL,
    issuer_name VARCHAR(100) NOT NULL,
    card_name VARCHAR(150) NOT NULL,
    status VARCHAR(30) NOT NULL,
    credit_limit BIGINT NOT NULL,
    baseline_performance BIGINT,
    max_benefit_limit BIGINT,
    annual_fee BIGINT,
    expiry_month CHAR(7),
    withdrawal_day INT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_test_card_user_hash UNIQUE (user_id, card_no_hash),
    CONSTRAINT fk_test_card_account
        FOREIGN KEY (withdrawal_account_id) REFERENCES account (account_id)
);

CREATE TABLE card_billing_statement (
    card_id BIGINT NOT NULL,
    billing_month CHAR(7) NOT NULL,
    billing_date DATE NOT NULL,
    total_balance BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    payment_date DATE,
    PRIMARY KEY (card_id, billing_month),
    CONSTRAINT fk_test_billing_statement_card
        FOREIGN KEY (card_id) REFERENCES card (card_id)
);

CREATE TABLE transaction_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    default_spending_type VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE `transaction` (
    transaction_id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_id BIGINT,
    card_id BIGINT,
    category_id BIGINT,
    transaction_date DATE NOT NULL,
    transaction_time TIME,
    transaction_type VARCHAR(30) NOT NULL,
    amount BIGINT NOT NULL,
    merchant_name VARCHAR(255),
    payment_method VARCHAR(30),
    spending_type VARCHAR(20),
    summary VARCHAR(255),
    memo VARCHAR(500),
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    CONSTRAINT fk_test_card_transaction_category
        FOREIGN KEY (category_id) REFERENCES transaction_category (category_id)
);

