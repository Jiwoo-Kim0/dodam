-- V11 card. card_no_encrypted는 실제 스키마와 같게 NOT NULL로 둔다(엔티티는 매핑하지 않는다).
CREATE TABLE card (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    withdrawal_account_id BIGINT NOT NULL,
    withdrawal_account_type VARCHAR(30) NOT NULL,
    financial_product_id BIGINT,
    card_no_encrypted VARBINARY(512) NOT NULL,
    card_no_hash CHAR(64) NOT NULL,
    card_no_masked VARCHAR(100) NOT NULL,
    issuer_code VARCHAR(30) NOT NULL,
    issuer_name VARCHAR(100) NOT NULL,
    card_name VARCHAR(150) NOT NULL,
    status VARCHAR(30) NOT NULL,
    credit_limit BIGINT NOT NULL,
    baseline_performance BIGINT,
    max_benefit_limit BIGINT,
    annual_fee BIGINT,
    expiry_month CHAR(7),
    withdrawal_day INT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_test_sub_card_user_hash UNIQUE (user_id, card_no_hash)
);

-- V30 subscription / subscription_payment_history (ERD 컬럼 전체, CHECK 포함, 외래키 제외).
CREATE TABLE subscription (
    subscription_id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    card_id BIGINT,
    name VARCHAR(150) NOT NULL,
    payment_amount BIGINT NOT NULL,
    billing_cycle VARCHAR(30) NOT NULL,
    payment_day INT,
    next_payment_date DATE,
    end_date DATE,
    status VARCHAR(30) NOT NULL,
    category VARCHAR(50),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    canceled_at TIMESTAMP,
    CONSTRAINT chk_test_subscription_billing_cycle CHECK (billing_cycle IN ('WEEKLY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT chk_test_subscription_status CHECK (status IN ('ACTIVE', 'PAUSED', 'CANCELED', 'EXPIRED')),
    CONSTRAINT chk_test_subscription_payment_amount CHECK (payment_amount > 0),
    CONSTRAINT chk_test_subscription_payment_day CHECK (payment_day IS NULL OR payment_day BETWEEN 1 AND 31),
    CONSTRAINT chk_test_subscription_dates
        CHECK (end_date IS NULL OR next_payment_date IS NULL OR next_payment_date <= end_date)
);

CREATE TABLE subscription_payment_history (
    payment_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id VARCHAR(100) NOT NULL,
    payment_date DATE NOT NULL,
    payment_amount BIGINT NOT NULL,
    result_code VARCHAR(50),
    retry_count INT NOT NULL DEFAULT 0,
    result_message VARCHAR(500),
    CONSTRAINT uk_test_subscription_payment_history_source UNIQUE (subscription_id, payment_date, payment_amount),
    CONSTRAINT chk_test_subscription_payment_history_amount CHECK (payment_amount > 0),
    CONSTRAINT chk_test_subscription_payment_history_retry_count CHECK (retry_count >= 0)
);
