-- S15P21D105-512/513/514: Subscription API 테스트가 쓰는 H2 fixture다. 실제 MySQL 마이그레이션(V30)을 대체하지 않는다.
--
-- `card`·`transaction`·`transaction_category`는 카드·거래·마이너스통장 테스트도 자기 컬럼만으로 만들고 지운다. 클래스 실행 순서와
-- 무관하게 같은 스키마가 되도록 여기서도 ERD 컬럼 전체로 다시 만든다. `user`·`account`·`card`로의 외래키는 다른 fixture와의
-- DROP 순서 의존을 피하려고 걸지 않는다(실제 V6·V11·V30에는 있다). CASCADE는 다른 fixture가 걸어 둔 외래키를 함께 지우기 위한 것이다.
--
-- 정기결제·카드·거래 행은 회원가입으로 만들어진 user_id를 알아야 하므로 테스트 코드가 넣는다.

DROP TABLE IF EXISTS subscription_payment_history CASCADE;
DROP TABLE IF EXISTS subscription CASCADE;
DROP TABLE IF EXISTS `transaction` CASCADE;
DROP TABLE IF EXISTS transaction_category CASCADE;
DROP TABLE IF EXISTS card CASCADE;

CREATE TABLE transaction_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    default_spending_type VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE `transaction` (
    transaction_id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_id BIGINT,
    card_id BIGINT,
    category_id BIGINT,
    transaction_date DATE NOT NULL,
    transaction_time TIME,
    transaction_type VARCHAR(30) NOT NULL,
    amount BIGINT NOT NULL,
    balance_after BIGINT,
    merchant_name VARCHAR(255),
    payment_method VARCHAR(30),
    spending_type VARCHAR(20),
    summary VARCHAR(255),
    memo VARCHAR(500),
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    internal_transfer BOOLEAN NOT NULL DEFAULT FALSE,
    source_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT chk_test_sub_transaction_amount CHECK (amount > 0),
    CONSTRAINT chk_test_sub_transaction_type CHECK (transaction_type IN ('INCOME', 'EXPENSE', 'TRANSFER')),
    CONSTRAINT fk_test_sub_transaction_category
        FOREIGN KEY (category_id) REFERENCES transaction_category (category_id)
);

