-- S15P21D105-504: 거래 조회·메모·카테고리·숨김 API 테스트가 쓰는 H2 fixture다.
-- 실제 MySQL 마이그레이션(V5)을 대체하지 않는다.
--
-- `transaction`, `transaction_category`는 카드·마이너스통장·상품 추천 테스트도 자기 컬럼만으로 만들고 지운다
-- (created_at 등 NOT NULL 컬럼이 빠져 있다). 클래스 실행 순서에 따라 그 스키마가 남아 있을 수 있으므로
-- 여기서 V5(ERD) 컬럼 전체로 다시 만든다. `account`·`card`·`user`로의 외래키는 다른 fixture와의 DROP 순서
-- 의존을 피하려고 걸지 않는다. 실제 V5에는 ERD대로 복합 외래키가 있다.
--
-- 거래 행은 회원가입으로 만들어진 user_id를 알아야 하므로 테스트 코드가 넣는다.

DROP TABLE IF EXISTS `transaction`;
DROP TABLE IF EXISTS transaction_category;

CREATE TABLE transaction_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    default_spending_type VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_test_transaction_category_spending_type
        CHECK (default_spending_type IS NULL OR default_spending_type IN ('FIXED', 'VARIABLE', 'NON_SPENDING'))
);

CREATE TABLE `transaction` (
    transaction_id VARCHAR(100) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_id BIGINT,
    card_id BIGINT,
    category_id BIGINT,
    transaction_date DATE NOT NULL,
    transaction_time TIME,
    transaction_type VARCHAR(30) NOT NULL,
    amount BIGINT NOT NULL,
    balance_after BIGINT,
    merchant_name VARCHAR(255),
    payment_method VARCHAR(30),
    spending_type VARCHAR(20),
    summary VARCHAR(255),
    memo VARCHAR(500),
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    source_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT chk_test_transaction_amount CHECK (amount > 0),
    CONSTRAINT chk_test_transaction_type CHECK (transaction_type IN ('INCOME', 'EXPENSE', 'TRANSFER')),
    CONSTRAINT chk_test_transaction_source_type CHECK (source_type IN ('SSAFY', 'MANUAL', 'SEED')),
    CONSTRAINT chk_test_transaction_spending_type
        CHECK (spending_type IS NULL OR spending_type IN ('FIXED', 'VARIABLE', 'NON_SPENDING')),
    CONSTRAINT fk_test_transaction_category
        FOREIGN KEY (category_id) REFERENCES transaction_category (category_id)
);

