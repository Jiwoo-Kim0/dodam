-- S15P21D105-531: 격리된 H2 테스트 DB에서 대출 조회 테스트가 쓰는 fixture다.
-- 실제 MySQL 마이그레이션(V13)을 대체하지 않으며 제약조건 검증도 대신하지 않는다.
--
-- `account`는 카드 fixture가 별도로 만들고 지우므로 여기서는 건드리지 않는다.
-- 대출 조회는 출금계좌를 노출하지 않아 `loan`에 account 외래키를 두지 않는다.
-- 테스트 클래스 실행 순서에 따라 서로의 스키마를 깨뜨리지 않도록 한 결정이다.
--
-- account_no_hash 는 테스트 실행 시 SensitiveNumberHasher 로 다시 채운다.
-- 기준일 의존을 피하려고 날짜는 테스트에서 갱신한다.

DROP TABLE IF EXISTS loan_repayment;
DROP TABLE IF EXISTS loan;

CREATE TABLE loan (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    withdrawal_account_id BIGINT NOT NULL,
    withdrawal_account_type VARCHAR(30) NOT NULL,
    financial_product_id BIGINT,
    institution_code VARCHAR(30) NOT NULL,
    institution_name VARCHAR(150) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(150) NOT NULL,
    loan_type VARCHAR(30) NOT NULL
        CHECK (loan_type IN ('CREDIT', 'MORTGAGE', 'JEONSE', 'AUTO', 'OTHER')),
    repayment_type VARCHAR(30) NOT NULL
        CHECK (repayment_type IN ('EQUAL_PRINCIPAL', 'EQUAL_PAYMENT', 'BULLET')),
    status VARCHAR(30) NOT NULL
        CHECK (status IN ('ACTIVE', 'OVERDUE', 'COMPLETED', 'CLOSED')),
    loan_period INT CHECK (loan_period IS NULL OR loan_period > 0),
    start_date DATE,
    maturity_date DATE,
    original_principal BIGINT NOT NULL CHECK (original_principal > 0),
    balance BIGINT NOT NULL CHECK (balance >= 0 AND balance <= original_principal),
    interest_rate DECIMAL(10,4) NOT NULL CHECK (interest_rate >= 0),
    repayment_day INT CHECK (repayment_day IS NULL OR repayment_day BETWEEN 1 AND 31),
    next_repayment_date DATE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_test_loan_user_hash UNIQUE (user_id, account_no_hash)
);

CREATE TABLE loan_repayment (
    loan_repayment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    repayment_date DATE NOT NULL,
    amount BIGINT NOT NULL CHECK (amount > 0),
    principal BIGINT CHECK (principal IS NULL OR principal >= 0),
    interest BIGINT CHECK (interest IS NULL OR interest >= 0),
    status VARCHAR(30) NOT NULL
        CHECK (status IN ('SCHEDULED', 'PAID', 'FAILED', 'OVERDUE')),
    failure_reason VARCHAR(500),
    CONSTRAINT fk_test_loan_repayment_loan FOREIGN KEY (loan_id) REFERENCES loan (loan_id)
);

