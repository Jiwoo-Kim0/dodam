-- S15P21D105-508: Goal API 테스트가 쓰는 H2 fixture다. 실제 MySQL 마이그레이션(V5, V7)을 대체하지 않는다.
--
-- `goal`·`saving_goal`·`spending_goal`은 소비 분석(507) fixture도 만들고 지운다. 클래스 실행 순서와 무관하게
-- 같은 스키마가 되도록 여기서도 ERD 컬럼 전체로 다시 만든다. `user` 외래키는 다른 fixture와의 DROP 순서 의존을
-- 피하려고 걸지 않는다(실제 V5에는 있다).
--
-- 목표 행은 회원가입으로 만들어진 user_id를 알아야 하므로 테스트 코드가 API로 만든다.

DROP TABLE IF EXISTS goal_history;
DROP TABLE IF EXISTS goal_account;
DROP TABLE IF EXISTS spending_goal;
DROP TABLE IF EXISTS saving_goal;
DROP TABLE IF EXISTS goal;
DROP TABLE IF EXISTS account CASCADE;

CREATE TABLE goal (
    goal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    current_amount BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    CONSTRAINT uk_test_goal_id_type UNIQUE (goal_id, type),
    CONSTRAINT chk_test_goal_type CHECK (type IN ('SAVING', 'SPENDING')),
    CONSTRAINT chk_test_goal_status CHECK (status IN ('ACTIVE', 'ACHIEVED', 'PAUSED', 'CANCELED')),
    CONSTRAINT chk_test_goal_current_amount CHECK (current_amount >= 0)
);

CREATE TABLE saving_goal (
    goal_id BIGINT PRIMARY KEY,
    goal_type VARCHAR(20) NOT NULL,
    target_amount BIGINT NOT NULL,
    target_date DATE NOT NULL,
    CONSTRAINT chk_test_saving_goal_type CHECK (goal_type = 'SAVING'),
    CONSTRAINT chk_test_saving_goal_target CHECK (target_amount > 0),
    CONSTRAINT fk_test_saving_goal_goal FOREIGN KEY (goal_id, goal_type) REFERENCES goal (goal_id, type)
);

CREATE TABLE spending_goal (
    goal_id BIGINT PRIMARY KEY,
    goal_type VARCHAR(20) NOT NULL,
    monthly_budget BIGINT NOT NULL,
    CONSTRAINT chk_test_spending_goal_type CHECK (goal_type = 'SPENDING'),
    CONSTRAINT chk_test_spending_goal_budget CHECK (monthly_budget > 0),
    CONSTRAINT fk_test_spending_goal_goal FOREIGN KEY (goal_id, goal_type) REFERENCES goal (goal_id, type)
);

-- 509 연결계좌. 다른 fixture와의 DROP 순서 의존을 피하려고 goal·account 외래키는 걸지 않는다(실제 V8에는 있다).
-- 계좌당 목표 1개 제약(uk_goal_account_account)은 서비스가 먼저 검사하지만 DB에서도 막는다.
CREATE TABLE goal_account (
    user_id BIGINT NOT NULL,
    goal_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    contribution_amount BIGINT,
    PRIMARY KEY (goal_id, account_id),
    CONSTRAINT uk_test_goal_account_account UNIQUE (account_id),
    CONSTRAINT chk_test_goal_account_type CHECK (account_type IN ('DEMAND_DEPOSIT', 'DEPOSIT', 'SAVINGS'))
);

-- 계좌 fixture와 같은 V3 스키마. 계좌 행은 테스트 코드가 넣는다.
CREATE TABLE account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    balance BIGINT NOT NULL,
    last_transaction_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'KRW',
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_test_goal_fixture_account_hash UNIQUE (user_id, account_no_hash)
);

-- 511 변화 이력. goal 외래키는 다른 fixture와의 DROP 순서 의존을 피하려고 걸지 않는다(실제 V9에는 있다).
CREATE TABLE goal_history (
    goal_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL,
    recorded_date DATE NOT NULL,
    current_amount BIGINT NOT NULL,
    progress_rate DECIMAL(10,4),
    forecast_date DATE,
    event VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_test_goal_history_amount CHECK (current_amount >= 0),
    CONSTRAINT chk_test_goal_history_rate CHECK (progress_rate IS NULL OR progress_rate BETWEEN 0 AND 100)
);
