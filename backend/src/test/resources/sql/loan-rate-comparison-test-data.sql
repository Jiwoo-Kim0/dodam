-- S15P21D105-533: 금리비교·고금리 판정 테스트 fixture.
--
-- 533은 loan과 product 도메인을 한 세션에서 함께 조회하는 첫 API다. 기존 fixture는 도메인별로 자기
-- 테이블만 DROP/CREATE하고 실행 순서가 서로의 스키마를 깨뜨리지 않도록 도메인 간 외래키를 두지 않는다.
-- 그 방침을 따라 이 파일이 네 테이블을 모두 소유하고 다른 fixture에 의존하지 않는다.
-- loan.financial_product_id는 외래키 없이 값만 맞춘다.
--
-- 실제 MySQL 마이그레이션(V10, V13)을 대체하지 않으며 제약조건 검증도 대신하지 않는다.
-- 시연 seed를 실행하거나 참조하지 않는다. 금액·금리는 계산을 손으로 검산할 수 있는 가상 값이다.
--
-- 기준일 2026-09-09, 상품 스냅샷 2026-09-03 기준으로 설계했다.

DROP TABLE IF EXISTS loan;
DROP TABLE IF EXISTS financial_product_option;
DROP TABLE IF EXISTS financial_product;
DROP TABLE IF EXISTS financial_company;

CREATE TABLE financial_company (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_code VARCHAR(30) NOT NULL,
    company_name VARCHAR(150) NOT NULL,
    sector VARCHAR(50)
);

CREATE TABLE financial_product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    external_product_code VARCHAR(100),
    product_type VARCHAR(30) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    join_way VARCHAR(255),
    saving_type VARCHAR(30),
    loan_type VARCHAR(30),
    special_condition TEXT,
    join_member TEXT,
    min_rate DECIMAL(10,4),
    max_rate DECIMAL(10,4),
    max_limit BIGINT,
    baseline_performance BIGINT,
    max_benefit_limit BIGINT,
    description TEXT,
    benefits JSON,
    synced_at TIMESTAMP NOT NULL
);

-- 실제 스키마와 달리 CHECK를 두지 않는다. 음수·역전 금리 방어 코드를 검증하려면 그런 값을 넣을 수
-- 있어야 한다. 이 통과를 MySQL 제약 검증으로 간주하지 않는다.
CREATE TABLE financial_product_option (
    product_option_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    term INT,
    rate DECIMAL(10,4),
    preferred_rate DECIMAL(10,4),
    rate_type VARCHAR(30),
    min_rate DECIMAL(10,4),
    max_rate DECIMAL(10,4),
    repayment_type VARCHAR(30),
    limit_amount BIGINT
);

CREATE TABLE loan (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    withdrawal_account_id BIGINT NOT NULL,
    withdrawal_account_type VARCHAR(30) NOT NULL,
    financial_product_id BIGINT,
    institution_code VARCHAR(30) NOT NULL,
    institution_name VARCHAR(150) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(150) NOT NULL,
    loan_type VARCHAR(30) NOT NULL
        CHECK (loan_type IN ('CREDIT', 'MORTGAGE', 'JEONSE', 'AUTO', 'OTHER')),
    repayment_type VARCHAR(30) NOT NULL
        CHECK (repayment_type IN ('EQUAL_PRINCIPAL', 'EQUAL_PAYMENT', 'BULLET')),
    status VARCHAR(30) NOT NULL
        CHECK (status IN ('ACTIVE', 'OVERDUE', 'COMPLETED', 'CLOSED')),
    loan_period INT,
    start_date DATE,
    maturity_date DATE,
    original_principal BIGINT NOT NULL,
    balance BIGINT NOT NULL,
    interest_rate DECIMAL(10,4) NOT NULL,
    repayment_day INT,
    next_repayment_date DATE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

