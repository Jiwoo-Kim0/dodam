-- S15P21D105-501: 계좌 목록·상세·잔액 API 테스트가 쓰는 H2 fixture다. 실제 MySQL 마이그레이션(V3)을 대체하지 않는다.
--
-- `account`는 카드·마이너스통장·Finance Data fixture도 자기 컬럼으로 다시 만들고, 예·적금 테스트는 엔티티가 만든
-- 스키마를 그대로 쓴다. 클래스 실행 순서에 따라 어느 스키마가 남아 있을지 알 수 없으므로 여기서 V3(ERD) 컬럼
-- 전체로 다시 만든다. account_no_encrypted 는 조회 API가 쓰지 않으므로 엔티티 읽기 경로가 원문 컬럼에 의존하지
-- 않음을 확인하기 위해 실제 스키마처럼 NOT NULL 로 둔다.
--
-- 계좌 행은 회원가입으로 만들어진 user_id와 해시 키에 의존하므로 테스트 코드가 넣는다.

DROP TABLE IF EXISTS account CASCADE;

CREATE TABLE account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    balance BIGINT NOT NULL,
    last_transaction_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'KRW',
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_test_account_user_account_hash UNIQUE (user_id, account_no_hash),
    CONSTRAINT chk_test_account_type
        CHECK (account_type IN ('DEMAND_DEPOSIT', 'MINUS', 'DEPOSIT', 'SAVINGS')),
    CONSTRAINT chk_test_account_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'CLOSED')),
    CONSTRAINT chk_test_account_balance_by_type
        CHECK ((account_type = 'MINUS' AND balance <= 0) OR (account_type <> 'MINUS' AND balance >= 0))
);
