-- Finance Data 통합 요약(S15P21D105-500) 테스트용 H2 스키마.
-- account·card·loan은 다른 도메인 소유 테이블이라 JPA 엔티티가 없거나 일부 컬럼만 매핑되어 있으므로,
-- ERD 컬럼명 기준으로 집계에 필요한 컬럼만 다시 만든다. 데이터는 테스트 코드가 사용자 ID를 알고 난 뒤 넣는다.
-- 다른 테스트 클래스(card·loan)도 자기 스키마를 다시 만들기 때문에 CASCADE로 지운다.

DROP TABLE IF EXISTS card CASCADE;
DROP TABLE IF EXISTS loan CASCADE;
DROP TABLE IF EXISTS account CASCADE;

CREATE TABLE account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bank_code VARCHAR(20) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    balance BIGINT NOT NULL,
    last_transaction_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'KRW',
    source_type VARCHAR(20) NOT NULL DEFAULT 'SEED',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE card (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    withdrawal_account_id BIGINT NOT NULL,
    withdrawal_account_type VARCHAR(30) NOT NULL,
    financial_product_id BIGINT,
    card_no_encrypted VARBINARY(512) NOT NULL,
    card_no_hash CHAR(64) NOT NULL,
    card_no_masked VARCHAR(100) NOT NULL,
    issuer_code VARCHAR(30) NOT NULL,
    issuer_name VARCHAR(100) NOT NULL,
    card_name VARCHAR(150) NOT NULL,
    status VARCHAR(30) NOT NULL,
    credit_limit BIGINT NOT NULL,
    baseline_performance BIGINT,
    max_benefit_limit BIGINT,
    annual_fee BIGINT,
    expiry_month CHAR(7),
    withdrawal_day INT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE loan (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    withdrawal_account_id BIGINT NOT NULL,
    withdrawal_account_type VARCHAR(30) NOT NULL,
    financial_product_id BIGINT,
    institution_code VARCHAR(30) NOT NULL,
    institution_name VARCHAR(150) NOT NULL,
    account_no_encrypted VARBINARY(512) NOT NULL,
    account_no_hash CHAR(64) NOT NULL,
    account_no_masked VARCHAR(100) NOT NULL,
    account_name VARCHAR(150) NOT NULL,
    loan_type VARCHAR(30) NOT NULL,
    repayment_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    loan_period INT,
    start_date DATE,
    maturity_date DATE,
    original_principal BIGINT NOT NULL,
    balance BIGINT NOT NULL,
    interest_rate DECIMAL(10,4) NOT NULL,
    repayment_day INT,
    next_repayment_date DATE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);
