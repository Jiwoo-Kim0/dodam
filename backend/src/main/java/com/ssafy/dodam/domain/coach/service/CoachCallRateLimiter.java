package com.ssafy.dodam.domain.coach.service;

/**
 * 사용자별 외부 AI 호출 예산.
 *
 * <p><b>왜 필요한가</b>: 코치 3종은 이 서비스에서 <b>외부 과금이 걸린 유일한 엔드포인트</b>다. 인증만
 * 통과하면 같은 사용자가 몇 번이든 부를 수 있었고, nginx의 레이트 리밋은 IP 기준인 데다 일반 API 버킷이
 * 초당 20건(시간당 72,000건)이라 비용 관점에서는 사실상 제한이 아니다. 막으려는 것은 공격자가 아니라
 * <b>FE의 렌더 루프·재시도 스크립트처럼 의도치 않게 같은 호출을 반복하는 코드</b>다.
 *
 * <p><b>무엇을 세는가</b>: HTTP 요청이 아니라 <b>실제로 과금되는 생성 호출만</b> 센다. 캐시 적중은 돈이
 * 들지 않으므로 예산을 깎지 않는다 — 화면을 다시 열었다고 사용자를 막을 이유가 없다.
 *
 * <p><b>구현은 절대 예외를 던지지 않는다.</b> 한도를 넘었는지 판단하지 못하는 상황이 코치 장애가 되면
 * 안 된다. 다만 캐시({@link CoachAnswerCache})와 달리 <b>모르면 통과</b>는 답이 아니다 — 저장소가 죽은
 * 순간은 캐시도 함께 죽어 모든 호출이 과금되는, 비용이 가장 큰 상황이기 때문이다. 그래서 구현은
 * 프로세스 내 카운터로 내려가 예산을 계속 건다({@code RedisCoachCallRateLimiter}).
 */
public interface CoachCallRateLimiter {

    /**
     * @param userId 호출 사용자. null이면 셀 수 없으므로 통과시킨다(인증 경로상 발생하지 않는다)
     * @return 예산이 남아 호출해도 되면 true. false면 호출자는 외부 API를 부르지 않고 템플릿으로 내려간다
     */
    boolean tryAcquire(Long userId);
}
