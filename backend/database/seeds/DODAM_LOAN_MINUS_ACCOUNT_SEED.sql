SELECT
  SUM(loan_row.financial_product_id IS NOT NULL) AS linked_product_count,
  SUM(loan_row.financial_product_id IS NULL) AS unlinked_product_count
FROM `loan` loan_row
JOIN tmp_dodam_523_loan_crypto crypto
  ON LOWER(crypto.account_no_hash) = loan_row.account_no_hash;
