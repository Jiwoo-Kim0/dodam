-- DODAM Loan, LoanRepayment, MinusAccount seed
-- Jira: S15P21D105-523
-- Dialect: MySQL 8.x
-- Schema basis: docs/ERD/DODAM_ERDCLOUD_IMPORT.sql (revision 2026-09-07)
-- Dependency: S15P21D105-491 User/Account seed
-- Dataset: 3,000 loans, 20,500 loan repayments, 1,000 minus accounts
-- Snapshot: 2026-09-07
--
-- Security prerequisites
-- ----------------------
-- This file never creates account-number plaintext, guesses an encryption
-- envelope, or stores encryption/HMAC keys. Before sourcing this file, the same
-- MySQL session must contain all three application-generated temporary tables
-- below.
--
-- 1. The 491 demand-deposit account natural keys:
--
--   CREATE TEMPORARY TABLE tmp_dodam_523_account_keys (
--     user_email VARCHAR(255) NOT NULL PRIMARY KEY,
--     account_no_hash CHAR(64) NOT NULL
--   );
--
-- It must contain seed.kmeans.u0001@dodam.invalid through
-- seed.kmeans.u4000@dodam.invalid. Each hash must be the lowercase account HMAC
-- generated by the same application codec/test key used for task 491. Loan
-- withdrawal accounts are resolved through these keys.
--
-- 2. Loan account-number crypto fixtures:
--
--   CREATE TEMPORARY TABLE tmp_dodam_523_loan_crypto (
--     seed_loan_code VARCHAR(50) NOT NULL PRIMARY KEY,
--     account_no_encrypted VARBINARY(512) NOT NULL,
--     account_no_hash CHAR(64) NOT NULL,
--     account_no_masked VARCHAR(100) NOT NULL
--   );
--
-- It must contain U0002_LOAN_PRIMARY through U4000_LOAN_PRIMARY for
-- even-numbered users and U0004_LOAN_SECONDARY through U4000_LOAN_SECONDARY for
-- every fourth user.
--
-- 3. Minus-account crypto fixtures:
--
--   CREATE TEMPORARY TABLE tmp_dodam_523_minus_crypto (
--     seed_account_code VARCHAR(50) NOT NULL PRIMARY KEY,
--     account_no_encrypted VARBINARY(512) NOT NULL,
--     account_no_hash CHAR(64) NOT NULL,
--     account_no_masked VARCHAR(100) NOT NULL
--   );
--
-- It must contain U0004_MINUS through U4000_MINUS for every fourth user.
--
-- Each encrypted value must come from the application's versioned AES-256-GCM
-- codec. Each hash must be a lowercase HMAC-SHA-256 hex value produced with a
-- separate test key. Each masked value must come from the application masker.
-- Identical synthetic inputs and test keys are required for every rerun.
--
-- Loan and minus hashes share one namespace with the 491 demand-deposit hashes.
-- The preflight therefore verifies that the 4,000 fixture hashes are mutually
-- distinct and that no minus hash already belongs to a non-MINUS account. That
-- second check exists because the account upsert below keys on
-- uk_account_user_account_hash: without it a colliding fixture would silently
-- rewrite a 491 demand-deposit account into a MINUS account.
--
-- Optional financial-product dependency
-- -------------------------------------
-- financial_product_id is resolved by company_code + product_type + product_name
-- when the existing finance_products SQL has been loaded. The ERD permits NULL,
-- so Loan/MinusAccount seed execution does not depend on product-catalog loading.
--
-- Account-table impact
-- --------------------
-- This file is the first seed to write account rows with account_type = 'MINUS'.
-- The 491 verification queries join their own crypto fixtures and are unaffected.
-- Downstream Account/Transaction work must expect four account types in the
-- cohort, not one.
--
-- MySQL TEMPORARY-table constraint
-- --------------------------------
-- MySQL raises ER_CANT_REOPEN_TABLE (1137) when a single statement references
-- the same TEMPORARY table more than once. Preflight metric collection and the
-- verification summary are therefore split into single-reference statements, and
-- the digit source for the 4,000-user cohort is an inline derived table instead
-- of a TEMPORARY table. The 491, 522, 492, 493 and subscription seeds keep the
-- multi-reference form but use regular (non-TEMPORARY) scratch tables instead,
-- dropped in their cleanup sections (see seeds/README.md).

