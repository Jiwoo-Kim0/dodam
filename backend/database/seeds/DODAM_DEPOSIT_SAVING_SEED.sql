  history.exception_month,
  history.exception_status
FROM tmp_dodam_524_users seed
JOIN (
  SELECT 0 AS variant_code, 'KB_KOOKMIN' AS bank_code,
         'KB국민은행' AS bank_name,
         'KB내맘대로적금' AS product_name,
         3.6000 AS interest_rate, 300000 AS monthly_amount
  UNION ALL
  SELECT 1, 'SHINHAN_BANK', '신한은행', '신한 스마트 적금', 3.4000, 500000
  UNION ALL
  SELECT 2, 'KAKAOBANK', '카카오뱅크', '자유적금', 3.8000, 200000
  UNION ALL
  SELECT 3, 'WOORI_BANK', '우리은행', 'WON 적금', 3.5000, 1000000
) variant
  ON variant.variant_code = MOD((seed.sequence_no DIV 2) - 1, 4)
JOIN (
  -- A 12-month contract is still running at the snapshot; the 6-month contract
  -- matured on its last installment. A closed account was terminated early and
  -- refunded, so it keeps its contract expiry date but holds no balance.
  SELECT 0 AS lifecycle_code, 'ACTIVE' AS account_status, 12 AS term_months
  UNION ALL SELECT 1, 'ACTIVE', 12
  UNION ALL SELECT 2, 'INACTIVE', 6
  UNION ALL SELECT 3, 'CLOSED', 12
) lifecycle
  ON lifecycle.lifecycle_code = MOD(((seed.sequence_no DIV 2) - 1) DIV 4, 4)
JOIN (
  SELECT 0 AS day_code, 10 AS payment_day
  UNION ALL SELECT 1, 15
  UNION ALL SELECT 2, 20
  UNION ALL SELECT 3, 25
  UNION ALL SELECT 4, 28
) payment
  ON payment.day_code = MOD((seed.sequence_no DIV 2) - 1, 5)
JOIN (
  -- Three of five histories are unbroken. The other two leave one installment
  -- unpaid: a failed automatic transfer and a deliberately skipped month.
  SELECT 0 AS history_code, 0 AS exception_count,
         CAST(NULL AS SIGNED) AS exception_month,
         CAST(NULL AS CHAR(30)) AS exception_status
  UNION ALL SELECT 1, 0, NULL, NULL
  UNION ALL SELECT 2, 0, NULL, NULL
  UNION ALL SELECT 3, 1, 4, 'FAILED'
  UNION ALL SELECT 4, 1, 5, 'SKIPPED'
) history
  ON history.history_code = MOD(((seed.sequence_no DIV 2) - 1) DIV 16, 5)
WHERE MOD(seed.sequence_no, 2) = 0;

