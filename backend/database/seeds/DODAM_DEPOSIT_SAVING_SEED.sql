DROP TEMPORARY TABLE IF EXISTS tmp_dodam_524_expected_savings;
CREATE TEMPORARY TABLE tmp_dodam_524_expected_savings (
  seed_account_code VARCHAR(50) NOT NULL,
  sequence_no INT NOT NULL,
  user_email VARCHAR(255) NOT NULL,
  bank_code VARCHAR(20) NOT NULL,
  bank_name VARCHAR(100) NOT NULL,
  product_name VARCHAR(255) NOT NULL,
  account_name VARCHAR(100) NOT NULL,
  account_status VARCHAR(30) NOT NULL,
  account_balance BIGINT NOT NULL,
  interest_rate DECIMAL(10,4) NOT NULL,
  monthly_amount BIGINT NOT NULL,
  payment_day INT NOT NULL,
  next_payment_date DATE NULL,
  term_months INT NOT NULL,
  opening_date DATE NOT NULL,
  expiry_date DATE NOT NULL,
  paid_installment_count INT NOT NULL,
  exception_month INT NULL,
  exception_status VARCHAR(30) NULL,
  PRIMARY KEY (seed_account_code),
  UNIQUE KEY uk_tmp_dodam_524_user_savings_code (user_email, seed_account_code),
  KEY idx_tmp_dodam_524_savings_sequence (sequence_no),
  CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'CLOSED')),
  CHECK (interest_rate >= 0),
  CHECK (monthly_amount > 0),
  CHECK (term_months > 0),
  -- Payment days are restricted to 10/15/20/25/28 so that the 2026-09
  -- installment always falls after the 2026-09-07 snapshot date. The day cycle
  -- length 5 is coprime with the 4-variant cycle, so product mix and payment day
  -- stay independent.
  CHECK (payment_day IN (10, 15, 20, 25, 28)),
  -- Opening in 2026-02 on the payment day makes the 2026-03 installment number 1
  -- and keeps the whole payment history inside the seeded window.
  CHECK (opening_date BETWEEN '2026-02-01' AND '2026-02-28'),
  CHECK (DAYOFMONTH(opening_date) = payment_day),
  CHECK (opening_date < expiry_date),
  -- Only a running account has a future installment; a matured one has passed
  -- its expiry date at the snapshot.
  CHECK ((account_status = 'ACTIVE'
          AND next_payment_date IS NOT NULL
          AND expiry_date > '2026-09-07')
      OR (account_status <> 'ACTIVE' AND next_payment_date IS NULL)),
  CHECK (account_status <> 'INACTIVE' OR expiry_date <= '2026-09-07'),
  -- A closed savings account has been paid out; a running one holds exactly the
  -- installments it actually paid.
  CHECK (account_status <> 'CLOSED' OR account_balance = 0),
  CHECK (account_status = 'CLOSED'
      OR account_balance = monthly_amount * paid_installment_count),
  CHECK (paid_installment_count BETWEEN 5 AND 6),
  CHECK ((exception_month IS NULL
          AND exception_status IS NULL
          AND paid_installment_count = 6)
      OR (exception_month BETWEEN 1 AND 6
          AND exception_status IN ('FAILED', 'SKIPPED')
          AND paid_installment_count = 5))
);

