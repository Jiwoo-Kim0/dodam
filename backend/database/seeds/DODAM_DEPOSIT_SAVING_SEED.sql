-- DODAM DepositSaving, SavingsPayment seed
-- Jira: S15P21D105-524
-- Dialect: MySQL 8.x
-- Schema basis: docs/ERD/DODAM_ERDCLOUD_IMPORT.sql (revision 2026-09-07)
-- Dependency: S15P21D105-491 User/Account seed
-- Dataset: 2,000 deposits, 2,000 savings, 13,000 savings payments
-- Snapshot: 2026-09-07
--
-- Security prerequisites
-- ----------------------
-- This file never creates account-number plaintext, guesses an encryption
-- envelope, or stores encryption/HMAC keys. Before sourcing this file, the same
-- MySQL session must contain all three application-generated temporary tables
-- below.
--
-- 1. The 491 demand-deposit account natural keys:
--
--   CREATE TEMPORARY TABLE tmp_dodam_524_account_keys (
--     user_email VARCHAR(255) NOT NULL PRIMARY KEY,
--     account_no_hash CHAR(64) NOT NULL
--   );
--
-- It must contain seed.kmeans.u0001@dodam.invalid through
-- seed.kmeans.u4000@dodam.invalid. Each hash must be the lowercase account HMAC
-- generated by the same application codec/test key used for task 491. Savings
-- withdrawal accounts are resolved through these keys. This is the same table
-- contract task 523 uses, so one fixture builder serves both files.
--
-- 2. Deposit account-number crypto fixtures:
--
--   CREATE TEMPORARY TABLE tmp_dodam_524_deposit_crypto (
--     seed_account_code VARCHAR(50) NOT NULL PRIMARY KEY,
--     account_no_encrypted VARBINARY(512) NOT NULL,
--     account_no_hash CHAR(64) NOT NULL,
--     account_no_masked VARCHAR(100) NOT NULL
--   );
--
-- It must contain U0001_DEPOSIT through U3999_DEPOSIT for odd-numbered users.
--
-- 3. Savings account-number crypto fixtures:
--
--   CREATE TEMPORARY TABLE tmp_dodam_524_savings_crypto (
--     seed_account_code VARCHAR(50) NOT NULL PRIMARY KEY,
--     account_no_encrypted VARBINARY(512) NOT NULL,
--     account_no_hash CHAR(64) NOT NULL,
--     account_no_masked VARCHAR(100) NOT NULL
--   );
--
-- It must contain U0002_SAVINGS through U4000_SAVINGS for even-numbered users.
--
-- Each encrypted value must come from the application's versioned AES-256-GCM
-- codec. Each hash must be a lowercase HMAC-SHA-256 hex value produced with a
-- separate test key. Each masked value must come from the application masker.
-- Identical synthetic inputs and test keys are required for every rerun.
--
-- Deposit and savings hashes share one namespace with the 491 demand-deposit
-- hashes and the 523 loan/minus hashes. The preflight therefore verifies that
-- the 4,000 fixture hashes are mutually distinct and that no fixture hash
-- already belongs to an account of a different type. That second check exists
-- because the account upsert below keys on uk_account_user_account_hash:
-- without it a colliding fixture would silently rewrite an existing account
-- into a DEPOSIT or SAVINGS account.
--
-- Optional financial-product dependency
-- -------------------------------------
-- financial_product_id is resolved by company_code + product_type + product_name
-- when the existing finance_products SQL has been loaded. The ERD permits NULL,
-- so DepositSaving seed execution does not depend on product-catalog loading.
--
-- Account-table impact
-- --------------------
-- This file is the first seed to write account rows with account_type 'DEPOSIT'
-- and 'SAVINGS'. Together with 491 (DEMAND_DEPOSIT) and 523 (MINUS) the cohort
-- now covers all four account types, so downstream Account/Dashboard work must
-- not assume a single type per user.
--
-- Balance convention
-- ------------------
-- account.balance holds principal only; accrued or matured interest is never
-- folded in. A deposit carries its principal until the account is closed, and a
-- savings account carries the sum of its paid installments. Closed accounts
-- hold 0. interest_rate is kept on deposit_saving for the products that
-- downstream rate comparisons need.
--
-- Payment window
-- --------------
-- Savings accounts open on 2026-02-<payment_day>, so installments 1 through 6
-- fall on the fixed 2026-03-01 .. 2026-08-31 window shared with 491/492/523 and
-- no installment is missing from the history. Running accounts add installment 7
-- in 2026-09, after the 2026-09-07 snapshot date.
--
-- MySQL TEMPORARY-table constraint
-- --------------------------------
-- MySQL raises ER_CANT_REOPEN_TABLE (1137) when a single statement references
-- the same TEMPORARY table more than once. Preflight metric collection and the
-- verification summary are therefore split into single-reference statements, and
-- the digit source for the 4,000-user cohort is an inline derived table instead
-- of a TEMPORARY table, exactly as in 523.

SET NAMES utf8mb4;
