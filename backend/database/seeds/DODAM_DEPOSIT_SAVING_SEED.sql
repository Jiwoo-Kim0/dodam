DROP TEMPORARY TABLE IF EXISTS tmp_dodam_524_users;
CREATE TEMPORARY TABLE tmp_dodam_524_users (
  sequence_no INT NOT NULL,
  synthetic_user_code CHAR(5) NOT NULL,
  user_email VARCHAR(255) NOT NULL,
  PRIMARY KEY (sequence_no),
  UNIQUE KEY uk_tmp_dodam_524_user_code (synthetic_user_code),
  UNIQUE KEY uk_tmp_dodam_524_user_email (user_email),
  CHECK (sequence_no BETWEEN 1 AND 4000)
);

INSERT INTO tmp_dodam_524_users (
  sequence_no,
  synthetic_user_code,
  user_email
)
SELECT
  numbers.sequence_no,
  CONCAT('U', LPAD(numbers.sequence_no, 4, '0')),
  CONCAT('seed.kmeans.u', LPAD(numbers.sequence_no, 4, '0'), '@dodam.invalid')
-- The digit source is an inline derived table, not a TEMPORARY table: MySQL
-- raises ER_CANT_REOPEN_TABLE when one TEMPORARY table is referenced more than
-- once in a single statement, which a four-way self cross join always does.
FROM (
  SELECT
    thousands.digit * 1000
      + hundreds.digit * 100
      + tens.digit * 10
      + ones.digit
      + 1 AS sequence_no
  FROM (
    SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
    UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7
    UNION ALL SELECT 8 UNION ALL SELECT 9
  ) thousands
  CROSS JOIN (
    SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
    UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7
    UNION ALL SELECT 8 UNION ALL SELECT 9
  ) hundreds
  CROSS JOIN (
    SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
    UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7
    UNION ALL SELECT 8 UNION ALL SELECT 9
  ) tens
  CROSS JOIN (
    SELECT 0 AS digit UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
    UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7
    UNION ALL SELECT 8 UNION ALL SELECT 9
  ) ones
) numbers
WHERE numbers.sequence_no BETWEEN 1 AND 4000;

