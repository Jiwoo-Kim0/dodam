-- Savings withdrawal accounts must still resolve to an active 491 demand
-- deposit. The fixture contract covers the whole cohort, so all 4,000 keys are
-- checked even though only the 2,000 savings rows consume one.
UPDATE tmp_dodam_524_check
SET matched_account_count = (
  SELECT COUNT(*)
  FROM tmp_dodam_524_users seed
  JOIN tmp_dodam_524_account_keys account_key
    ON account_key.user_email = seed.user_email
  JOIN `user` user_row ON user_row.email = seed.user_email
  JOIN `account` account_row
    ON account_row.user_id = user_row.user_id
   AND account_row.account_no_hash = LOWER(account_key.account_no_hash)
   AND account_row.account_type = 'DEMAND_DEPOSIT'
   AND account_row.status = 'ACTIVE'
);

