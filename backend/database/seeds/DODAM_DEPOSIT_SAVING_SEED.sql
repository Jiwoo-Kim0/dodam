-- Unmapped, empty, or non-lowercase-hex fixtures are all counted as invalid.
UPDATE tmp_dodam_524_check
SET invalid_key_count =
  (SELECT COUNT(*)
   FROM tmp_dodam_524_account_keys account_key
   LEFT JOIN tmp_dodam_524_users seed
     ON seed.user_email = account_key.user_email
   WHERE seed.user_email IS NULL
      OR account_key.account_no_hash IS NULL
