          OR withdrawal_row.account_id IS NULL
          OR saving_row.monthly_amount IS NULL
          OR saving_row.monthly_amount <= 0
          OR saving_row.payment_day NOT BETWEEN 1 AND 31))
    OR account_row.account_no_encrypted IS NULL
    OR OCTET_LENGTH(account_row.account_no_encrypted) = 0
    OR CHAR_LENGTH(account_row.account_no_hash) <> 64
    OR account_row.account_no_hash NOT REGEXP '^[0-9a-f]{64}$'
    OR account_row.account_no_masked IS NULL
    OR TRIM(account_row.account_no_masked) = '');

-- Expected: 0 SavingsPayment domain violations. Every installment must fall
-- inside its contract period and belong to a savings account.
SELECT COUNT(*) AS savings_payment_contract_violation_count
FROM `savings_payment` payment_row
JOIN `deposit_saving` saving_row
  ON saving_row.account_id = payment_row.deposit_saving_id
JOIN `account` account_row ON account_row.account_id = saving_row.account_id
JOIN tmp_dodam_524_savings_crypto crypto
  ON LOWER(crypto.account_no_hash) = account_row.account_no_hash
WHERE payment_row.account_type <> 'SAVINGS'
   OR saving_row.account_type <> 'SAVINGS'
   OR payment_row.status NOT IN ('SCHEDULED', 'PAID', 'FAILED', 'SKIPPED')
   OR payment_row.amount <= 0
   OR payment_row.installment_number <= 0
   OR payment_row.payment_date < saving_row.opening_date
   OR payment_row.payment_date > saving_row.expiry_date;

-- Expected: 0. account.balance must equal the installments that were actually
-- paid, and a closed savings account must hold nothing.
SELECT COUNT(*) AS savings_balance_mismatch_count
FROM (
  SELECT
    account_row.account_id,
    account_row.status,
    account_row.balance,
    saving_row.monthly_amount,
    SUM(payment_row.status = 'PAID') AS paid_count
  FROM `savings_payment` payment_row
  JOIN `deposit_saving` saving_row
    ON saving_row.account_id = payment_row.deposit_saving_id
  JOIN `account` account_row ON account_row.account_id = saving_row.account_id
  JOIN tmp_dodam_524_savings_crypto crypto
    ON LOWER(crypto.account_no_hash) = account_row.account_no_hash
  GROUP BY account_row.account_id, account_row.status, account_row.balance,
           saving_row.monthly_amount
) totals
WHERE (totals.status = 'CLOSED' AND totals.balance <> 0)
   OR (totals.status <> 'CLOSED'
       AND totals.balance <> totals.monthly_amount * totals.paid_count);

-- Expected: 0. No 491 demand-deposit account may have been rewritten into a
-- deposit or savings account by this run.
SELECT COUNT(*) AS demand_deposit_regression_count
FROM `account` account_row
JOIN `user` user_row ON user_row.user_id = account_row.user_id
JOIN tmp_dodam_524_account_keys account_key
  ON account_key.user_email = user_row.email
 AND LOWER(account_key.account_no_hash) = account_row.account_no_hash
WHERE account_row.account_type <> 'DEMAND_DEPOSIT';

