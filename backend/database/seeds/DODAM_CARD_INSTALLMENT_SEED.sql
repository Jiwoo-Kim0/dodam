DROP TABLE IF EXISTS tmp_dodam_522_preflight;
CREATE TABLE tmp_dodam_522_preflight (
  ready TINYINT NOT NULL,
  expected_user_count INT NOT NULL,
  persisted_user_count INT NOT NULL,
  account_key_count INT NOT NULL,
  matched_account_count INT NOT NULL,
  expected_card_count INT NOT NULL,
  card_crypto_count INT NOT NULL,
  matched_card_crypto_count INT NOT NULL,
  invalid_key_count INT NOT NULL,
  distinct_card_hash_count INT NOT NULL,
  PRIMARY KEY (ready),
  CHECK (ready = 1),
  CHECK (expected_user_count = 4000),
  CHECK (persisted_user_count = 4000),
  CHECK (account_key_count = 4000),
  CHECK (matched_account_count = 4000),
  CHECK (expected_card_count = 6000),
  CHECK (card_crypto_count = 6000),
  CHECK (matched_card_crypto_count = 6000),
  CHECK (invalid_key_count = 0),
  CHECK (distinct_card_hash_count = 6000)
);

-- Missing prerequisite tables fail here before START TRANSACTION. Incomplete or
-- malformed fixtures fail the preflight CHECK constraints before permanent DML.
INSERT INTO tmp_dodam_522_preflight (
  ready,
  expected_user_count,
  persisted_user_count,
  account_key_count,
  matched_account_count,
  expected_card_count,
  card_crypto_count,
  matched_card_crypto_count,
  invalid_key_count,
  distinct_card_hash_count
)
SELECT
  CASE WHEN
    checks.expected_user_count = 4000
      AND checks.persisted_user_count = 4000
      AND checks.account_key_count = 4000
      AND checks.matched_account_count = 4000
      AND checks.expected_card_count = 6000
      AND checks.card_crypto_count = 6000
      AND checks.matched_card_crypto_count = 6000
      AND checks.invalid_key_count = 0
      AND checks.distinct_card_hash_count = 6000
    THEN 1
    ELSE 0
  END,
  checks.expected_user_count,
  checks.persisted_user_count,
  checks.account_key_count,
  checks.matched_account_count,
  checks.expected_card_count,
  checks.card_crypto_count,
  checks.matched_card_crypto_count,
  checks.invalid_key_count,
  checks.distinct_card_hash_count
FROM (
  SELECT
    (SELECT COUNT(*) FROM tmp_dodam_522_users) AS expected_user_count,
    (SELECT COUNT(*)
     FROM tmp_dodam_522_users seed
     JOIN `user` user_row ON user_row.email = seed.user_email)
      AS persisted_user_count,
    (SELECT COUNT(*) FROM tmp_dodam_522_account_keys) AS account_key_count,
    (SELECT COUNT(*)
     FROM tmp_dodam_522_users seed
     JOIN tmp_dodam_522_account_keys account_key
       ON account_key.user_email = seed.user_email
     JOIN `user` user_row ON user_row.email = seed.user_email
     JOIN `account` account_row
       ON account_row.user_id = user_row.user_id
      AND account_row.account_no_hash = LOWER(account_key.account_no_hash)
      AND account_row.account_type = 'DEMAND_DEPOSIT'
      AND account_row.status = 'ACTIVE') AS matched_account_count,
    (SELECT COUNT(*) FROM tmp_dodam_522_expected_cards) AS expected_card_count,
    (SELECT COUNT(*) FROM tmp_dodam_522_card_crypto) AS card_crypto_count,
    (SELECT COUNT(*)
     FROM tmp_dodam_522_expected_cards expected
     JOIN tmp_dodam_522_card_crypto crypto
       ON crypto.seed_card_code = expected.seed_card_code)
      AS matched_card_crypto_count,
    ((SELECT COUNT(*)
      FROM tmp_dodam_522_account_keys account_key
      LEFT JOIN tmp_dodam_522_users seed
        ON seed.user_email = account_key.user_email
      WHERE seed.user_email IS NULL
         OR account_key.account_no_hash IS NULL
         OR CHAR_LENGTH(account_key.account_no_hash) <> 64
         OR LOWER(account_key.account_no_hash) NOT REGEXP '^[0-9a-f]{64}$'
         OR CAST(account_key.account_no_hash AS BINARY)
           <> CAST(LOWER(account_key.account_no_hash) AS BINARY))
     +
     (SELECT COUNT(*)
      FROM tmp_dodam_522_card_crypto crypto
      LEFT JOIN tmp_dodam_522_expected_cards expected
        ON expected.seed_card_code = crypto.seed_card_code
      WHERE expected.seed_card_code IS NULL
         OR crypto.card_no_encrypted IS NULL
         OR OCTET_LENGTH(crypto.card_no_encrypted) = 0
         OR crypto.card_no_hash IS NULL
         OR CHAR_LENGTH(crypto.card_no_hash) <> 64
         OR LOWER(crypto.card_no_hash) NOT REGEXP '^[0-9a-f]{64}$'
         OR CAST(crypto.card_no_hash AS BINARY)
           <> CAST(LOWER(crypto.card_no_hash) AS BINARY)
         OR crypto.card_no_masked IS NULL
         OR TRIM(crypto.card_no_masked) = '')) AS invalid_key_count,
    (SELECT COUNT(DISTINCT LOWER(crypto.card_no_hash))
     FROM tmp_dodam_522_card_crypto crypto) AS distinct_card_hash_count
) checks;

START TRANSACTION;

