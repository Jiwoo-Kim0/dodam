-- Expected: 0 Card/Installment domain and FK contract violations.
SELECT COUNT(*) AS card_contract_violation_count
FROM `card` card_row
JOIN tmp_dodam_522_card_crypto crypto
  ON LOWER(crypto.card_no_hash) = card_row.card_no_hash
LEFT JOIN `account` account_row
  ON account_row.user_id = card_row.user_id
 AND account_row.account_id = card_row.withdrawal_account_id
 AND account_row.account_type = card_row.withdrawal_account_type
WHERE card_row.withdrawal_account_type <> 'DEMAND_DEPOSIT'
   OR account_row.account_id IS NULL
   OR card_row.status NOT IN ('ACTIVE', 'SUSPENDED', 'EXPIRED', 'CANCELED')
   OR card_row.credit_limit < 0
   OR card_row.baseline_performance < 0
   OR card_row.max_benefit_limit < 0
   OR card_row.annual_fee < 0
   OR card_row.withdrawal_day NOT BETWEEN 1 AND 31
   OR card_row.card_no_encrypted IS NULL
   OR OCTET_LENGTH(card_row.card_no_encrypted) = 0
   OR CHAR_LENGTH(card_row.card_no_hash) <> 64
   OR card_row.card_no_hash NOT REGEXP '^[0-9a-f]{64}$'
   OR card_row.card_no_masked IS NULL
   OR TRIM(card_row.card_no_masked) = '';

SELECT COUNT(*) AS installment_contract_violation_count
FROM `installment` installment_row
JOIN `card` card_row ON card_row.card_id = installment_row.card_id
JOIN tmp_dodam_522_card_crypto crypto
  ON LOWER(crypto.card_no_hash) = card_row.card_no_hash
WHERE installment_row.status NOT IN ('ACTIVE', 'COMPLETED', 'CANCELED', 'OVERDUE')
   OR installment_row.total_amount <= 0
   OR installment_row.months <= 0
   OR installment_row.remaining_principal < 0
   OR installment_row.remaining_months NOT BETWEEN 0 AND installment_row.months
   OR installment_row.monthly_amount <= 0
   OR installment_row.fee_rate < 0
   OR installment_row.purchase_date > installment_row.first_payment_date
   OR (installment_row.status = 'COMPLETED'
       AND (installment_row.remaining_principal <> 0
            OR installment_row.remaining_months <> 0
            OR installment_row.next_payment_date IS NOT NULL))
   OR (installment_row.status IN ('ACTIVE', 'OVERDUE')
       AND installment_row.next_payment_date IS NULL);

