-- DODAM Card and Installment seed
-- Jira: S15P21D105-522
-- Dialect: MySQL 8.x
-- Schema basis: docs/ERD/DODAM_ERDCLOUD_IMPORT.sql (revision 2026-09-07)
-- Dependency: S15P21D105-491 User/Account seed
-- Dataset: 6,000 cards for 4,000 users and 3,000 installments
-- Snapshot: 2026-09-07
--
-- Security prerequisites
-- ----------------------
-- This file never creates card/account-number plaintext, guesses an encryption
-- envelope, or stores encryption/HMAC keys. Before sourcing this file, the same
-- MySQL session must contain both application-generated scratch tables (regular tables, not TEMPORARY) below.
--
-- 1. The 491 demand-deposit account natural keys:
--
--   CREATE TABLE tmp_dodam_522_account_keys (
--     user_email VARCHAR(255) NOT NULL PRIMARY KEY,
--     account_no_hash CHAR(64) NOT NULL
--   );
--
-- It must contain seed.kmeans.u0001@dodam.invalid through
-- seed.kmeans.u4000@dodam.invalid. Each hash must be the lowercase account HMAC
-- generated by the same application codec/test key used for task 491.
--
-- 2. Card-number crypto fixtures:
--
--   CREATE TABLE tmp_dodam_522_card_crypto (
--     seed_card_code VARCHAR(50) NOT NULL PRIMARY KEY,
--     card_no_encrypted VARBINARY(512) NOT NULL,
--     card_no_hash CHAR(64) NOT NULL,
--     card_no_masked VARCHAR(100) NOT NULL
--   );
--
-- It must contain U0001_CARD_PRIMARY through U4000_CARD_PRIMARY and
-- U0002_CARD_SECONDARY through U4000_CARD_SECONDARY for even-numbered users.
-- Each encrypted value must come from the application's versioned AES-256-GCM
-- codec. Each hash must be a lowercase HMAC-SHA-256 hex value produced with a
-- separate test key. Each masked value must come from the application masker.
-- Identical synthetic inputs and test keys are required for every rerun.
--
-- The preflight constraints stop all permanent writes unless all expected users,
-- active withdrawal accounts, account keys, and card crypto fixtures match.
--
-- Optional financial-product dependency
-- -------------------------------------
-- financial_product_id is resolved by company_code + product_type + product_name
-- when the existing finance_products SQL has been loaded. The ERD permits NULL,
-- so Card/Installment seed execution does not depend on product-catalog loading.

-- MySQL TEMPORARY-table constraint
-- --------------------------------
-- MySQL raises ER_CANT_REOPEN_TABLE (1137) when a single statement references
-- the same TEMPORARY table more than once (self joins, two scalar subqueries,
-- EXISTS gates). This file's scratch tables (tmp_dodam_*) and the application
-- fixture tables above are therefore regular tables, not TEMPORARY, and the
-- cleanup section at the end drops them all. Verified on MySQL 8.0.46.
--
SET NAMES utf8mb4;
