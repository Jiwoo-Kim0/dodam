DROP TABLE IF EXISTS tmp_dodam_522_users;
CREATE TABLE tmp_dodam_522_users (
  sequence_no INT NOT NULL,
  synthetic_user_code CHAR(5) NOT NULL,
  user_email VARCHAR(255) NOT NULL,
  PRIMARY KEY (sequence_no),
  UNIQUE KEY uk_tmp_dodam_522_user_code (synthetic_user_code),
  UNIQUE KEY uk_tmp_dodam_522_user_email (user_email),
  CHECK (sequence_no BETWEEN 1 AND 4000)
);

INSERT INTO tmp_dodam_522_users (
  sequence_no,
  synthetic_user_code,
  user_email
)
SELECT
  numbers.sequence_no,
  CONCAT('U', LPAD(numbers.sequence_no, 4, '0')),
  CONCAT('seed.kmeans.u', LPAD(numbers.sequence_no, 4, '0'), '@dodam.invalid')
FROM (
  SELECT
    thousands.digit * 1000
      + hundreds.digit * 100
      + tens.digit * 10
      + ones.digit
      + 1 AS sequence_no
  FROM tmp_dodam_522_digit thousands
  CROSS JOIN tmp_dodam_522_digit hundreds
  CROSS JOIN tmp_dodam_522_digit tens
  CROSS JOIN tmp_dodam_522_digit ones
) numbers
WHERE numbers.sequence_no BETWEEN 1 AND 4000;

