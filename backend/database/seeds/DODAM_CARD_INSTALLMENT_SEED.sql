-- 2. Installment: the ERD has no dedicated natural-key constraint, so existing
-- seed rows are updated using a stable card+merchant+purchase+amount+months key.
UPDATE `installment` installment_row
JOIN `card` card_row ON card_row.card_id = installment_row.card_id
JOIN tmp_dodam_522_card_crypto crypto
  ON LOWER(crypto.card_no_hash) = card_row.card_no_hash
JOIN tmp_dodam_522_expected_installments expected
  ON expected.seed_card_code = crypto.seed_card_code
 AND expected.merchant_name = installment_row.merchant_name
 AND expected.purchase_date = installment_row.purchase_date
 AND expected.total_amount = installment_row.total_amount
 AND expected.months = installment_row.months
SET
  installment_row.remaining_principal = expected.remaining_principal,
  installment_row.remaining_months = expected.remaining_months,
  installment_row.monthly_amount = expected.monthly_amount,
  installment_row.fee_rate = expected.fee_rate,
  installment_row.first_payment_date = expected.first_payment_date,
  installment_row.next_payment_date = expected.next_payment_date,
  installment_row.status = expected.status,
  installment_row.updated_at = '2026-09-07 09:00:00'
WHERE EXISTS (
  SELECT 1 FROM tmp_dodam_522_preflight preflight WHERE preflight.ready = 1
);

