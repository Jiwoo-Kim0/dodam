SELECT
  user_row.user_id,
  account_row.account_id,
  account_row.account_type,
  product.product_id,
  crypto.card_no_encrypted,
  LOWER(crypto.card_no_hash),
  crypto.card_no_masked,
  expected.issuer_code,
  expected.issuer_name,
  expected.card_name,
  expected.status,
  expected.credit_limit,
  expected.baseline_performance,
  expected.max_benefit_limit,
  expected.annual_fee,
  expected.expiry_month,
  expected.withdrawal_day,
  '2026-09-07 09:00:00',
  '2026-09-07 09:00:00'
FROM tmp_dodam_522_expected_cards expected
JOIN tmp_dodam_522_card_crypto crypto
  ON crypto.seed_card_code = expected.seed_card_code
JOIN tmp_dodam_522_account_keys account_key
  ON account_key.user_email = expected.user_email
JOIN `user` user_row ON user_row.email = expected.user_email
JOIN `account` account_row
  ON account_row.user_id = user_row.user_id
 AND account_row.account_no_hash = LOWER(account_key.account_no_hash)
